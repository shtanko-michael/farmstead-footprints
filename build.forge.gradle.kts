plugins {
    // ModDevGradle legacy flavour: MinecraftForge 1.17–1.20.1 with official mappings and SRG reobfuscation
    id("net.neoforged.moddev.legacyforge") version "2.0.148"
    id("neoforge-mutex")
}

version = "${sc.properties["mod.version"]}+${sc.current.version}"
base.archivesName = "${sc.properties["mod.file"]}-forge"

val requiredJava = when {
    sc.current.parsed >= "1.20.5" -> JavaVersion.VERSION_21
    sc.current.parsed >= "1.18" -> JavaVersion.VERSION_17
    else -> JavaVersion.VERSION_1_8
}

val modId = sc.properties["mod.id"]

repositories {
    fun strictMaven(url: String, alias: String, vararg groups: String) = exclusiveContent {
        forRepository { maven(url) { name = alias } }
        filter { groups.forEach(::includeGroup) }
    }
    strictMaven("https://www.cursemaven.com", "CurseForge", "curse.maven")
    strictMaven("https://api.modrinth.com/maven", "Modrinth", "maven.modrinth")
}

dependencies {
    // Forge 1.20.1 does not bundle MixinExtras or run the Mixin annotation processor on its own
    annotationProcessor("org.spongepowered:mixin:0.8.5:processor")
    compileOnly(annotationProcessor("io.github.llamalad7:mixinextras-common:0.4.1")!!)
    implementation(jarJar("io.github.llamalad7:mixinextras-forge:0.4.1")!!)
}

legacyForge {
    version = sc.properties["deps.forge_loader"]

    mods {
        register(modId) {
            sourceSet(sourceSets.main.get())
        }
    }

    runs {
        register("client") {
            gameDirectory = rootProject.file("run/${sc.current.project}/client")
            client()
            // `-PquickPlay=localhost:25600` joins a server straight away, `-PmcUser=Name` picks the offline name
            providers.gradleProperty("quickPlay").orNull?.let { programArguments.addAll("--quickPlayMultiplayer", it) }
            providers.gradleProperty("mcUser").orNull?.let { programArguments.addAll("--username", it) }
            // `-PclientSize=1920x1080` sets the window size (screenshots, video capture)
            providers.gradleProperty("clientSize").orNull?.split("x")?.let { programArguments.addAll("--width", it[0], "--height", it[1]) }
            // `-PtestHooks` lets the test runner request screenshots through files (see TestHooks)
            if (providers.gradleProperty("testHooks").isPresent) jvmArguments.add("-Dfarmstead.testhooks=true")
            // quickPlay on Forge 1.20.1 skips the FML handshake; TestHooks joins from the title screen instead
            providers.gradleProperty("testJoin").orNull?.let { jvmArguments.add("-Dfarmstead.testhooks.join=$it") }
        }

        register("server") {
            gameDirectory = rootProject.file("run/${sc.current.project}/server")
            server()
            programArguments.add("--nogui") // the Swing console window crashes under heavy RCON/log traffic
        }
    }
}

// The Mixin annotation processor writes no mappings when a mod has no mixins yet,
// and reobf then fails on the missing file, so the refmap is wired up only when needed.
val mixinsJson = rootProject.file("src/main/resources/$modId.mixins.json")
val hasMixins = mixinsJson.exists() &&
    Regex(""""(mixins|client|server)"\s*:\s*\[\s*"""").containsMatchIn(mixinsJson.readText())
if (hasMixins) {
    mixin {
        add(sourceSets.main.get(), "$modId.refmap.json")
        config("$modId.mixins.json")
    }
}

// Loader-specific code lives in `<package>/platform/<loader>/`; other loaders' packages are left out
sourceSets.main {
    java {
        exclude("**/platform/fabric/**")
        exclude("**/platform/neoforge/**")
    }
}

java {
    withSourcesJar()
    targetCompatibility = requiredJava
    sourceCompatibility = requiredJava

    toolchain {
        vendor = JvmVendorSpec.ADOPTIUM
        languageVersion = JavaLanguageVersion.of(requiredJava.majorVersion)
    }
}

tasks {
    processResources {
        val modId = sc.properties["mod.id"]
        fun MutableMap<String, String>.register(key: String, value: String) {
            inputs.property(key, value)
            set(key, value)
        }

        val props = buildMap {
            register("id", modId)
            register("name", sc.properties["mod.name"])
            register("homepage", sc.properties["mod.homepage"])
            register("sources", sc.properties["mod.sources"])
            register("issues", sc.properties["mod.issues"])
            register("version", sc.properties["mod.version"])
            register("minecraft", sc.properties["mod.mc_compat"])
        }

        filesMatching("META-INF/mods.toml") { expand(props) }

        val mixinJava = "JAVA_${requiredJava.majorVersion}"
        filesMatching("*.mixins.json") {
            expand("java" to mixinJava, "extraClient" to "")
            // Forge 1.20.1 runs on SRG names, so mixins need the refmap generated by the annotation processor
            filter { line ->
                if (line.trimStart().startsWith("\"package\"")) "$line\n  \"refmap\": \"$modId.refmap.json\"," else line
            }
        }

        exclude("fabric.mod.json", "META-INF/neoforge.mods.toml", "*.ct", "*.classtweaker")
    }

    named("createMinecraftArtifacts") {
        dependsOn("stonecutterGenerate")
    }

    jar {
        manifest.attributes["MixinConfigs"] = "${sc.properties["mod.id"]}.mixins.json"
    }

    withType<Jar> {
        val name = sc.properties["mod.id"]
        inputs.property("mod_id", name)
        from("../../LICENSE") { rename { "$it-$name" } }
    }

    register<Copy>("buildAndCollect") {
        group = "build"
        description = "Builds mod jars and copies results to `build/libs/{mod version}/`"

        inputs.property("version", sc.properties["mod.version"])
        // reobfJar produces the SRG-mapped jar that Forge 1.20.1 actually loads
        from(named<Jar>("reobfJar").flatMap { it.archiveFile }, named<Jar>("sourcesJar").flatMap { it.archiveFile })
        into(rootProject.layout.buildDirectory.file("libs/${sc.properties["mod.version"]}"))
    }
}
